// sanitizeTest is a case of the sanitizer tables. Their expected outputs
// were produced by bluemonday v1.0.27, with the extensions of
// markup.NewSanitizer at commit 764930482 for the Markdown policy, so that
// Policy is checked to be identical to the sanitizer it replaced.
type sanitizeTest struct {
	// name is the behavior the input tests.
	name string
	in   string
	// want is the output of the base policy, NewPolicy(false, nil).
	want string
	// wantMarkdown is the output of NewPolicy(true, nil) if it differs.
	wantMarkdown string
}

func testSanitize(t *testing.T, tests []sanitizeTest) {
	t.Helper()
	base, markdown := NewPolicy(false, nil), NewPolicy(true, nil)
	for _, test := range tests {
		wantMarkdown := test.wantMarkdown
		if wantMarkdown == "" {
			wantMarkdown = test.want
		}
		assert.Equal(t, test.want, string(base.AppendSanitized(nil, []byte(test.in))), "base policy, %s: %q", test.name, test.in)
		assert.Equal(t, wantMarkdown, string(markdown.AppendSanitized(nil, []byte(test.in))), "Markdown policy, %s: %q", test.name, test.in)
	}
}

