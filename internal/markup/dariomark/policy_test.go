func TestPolicy_Sanitizer(t *testing.T) {
	s := NewPolicy(true, []string{"ftp", "data"}).Sanitizer()
	for raw, want := range map[string]bool{
		"https://example.com/":           true,
		"HTTP://example.com/":            true,
		"mailto:a@example.com":           true,
		"ftp://example.com/":             true,
		"javascript:alert(1)":            false,
		"data:image/png;base64,iVBORw0K": true,
		"data:text/html,x":               false,
	} {
		u, err := url.Parse(raw)
		require.NoError(t, err)
		assert.Equal(t, want, s.AllowURLScheme(u), raw)
	}
	assert.True(t, s.Text.MatchString("A b"))
	assert.False(t, s.Text.MatchString("a<b"))
	assert.True(t, s.CodeClass.MatchString("language-go"))
	assert.False(t, s.CodeClass.MatchString("language-go x"))

	// Without the Markdown rules, data URIs are not allowed.
	s = NewPolicy(false, nil).Sanitizer()
	u, err := url.Parse("data:image/png;base64,iVBORw0K")
	require.NoError(t, err)
	assert.False(t, s.AllowURLScheme(u))
}
